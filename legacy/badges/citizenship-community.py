def requirements():
    return [
        ["1. Discuss with your counselor what citizenship in the community means and what it takes to be a good citizen, including rights, duties, and obligations."],
        ["2. Do the following:", [
            "a. Locate chief government buildings, fire/police stations, hospitals, parks, playgrounds, recreation areas, trails, and historical points of interest on a map.",
            "b. Chart the organization of your local or state government, showing top offices and whether they are elected or appointed."
        ]],
        ["3. Do the following:", [
            "a. Attend a city, town, or county council or school board meeting OR attend a municipal, county, or state court session.",
            "b. Choose an issue discussed at the meeting where opinions differed, and explain why you agree with one opinion more than another."
        ]],
        ["4. Choose an important issue for the citizens of your community, then do the following:", [
            "a. Identify which branch of local government is responsible for this issue.",
            "b. With approval, interview one person from that branch and find out what is being done about the issue and how young people can help.",
            "c. Share what you learned with your counselor."
        ]],
        ["5. Watch a movie that shows how the actions of one individual or group can positively impact a community. Discuss what you learned about being a valuable community member."],
        ["6. List services in your community funded by taxpayers (e.g., library, recreation center, public safety) and explain why they are important."],
        ["7. Do the following:", [
            "a. Identify three charitable organizations outside Scouting that bring people in your community together for the common good.",
            "b. Pick ONE of the organizations, find out more using resources like the Internet, newspapers, or volunteers.",
            "c. With approval, contact the organization and volunteer at least eight hours. Discuss what you learned afterward."
        ]],
        ["8. Develop a public presentation (e.g., video, slide show, speech, digital presentation, or photo exhibit) about important aspects of your community, including its history, cultures, ethnic groups, best features, and challenges. Present it to your counselor or a group."]
    ]
